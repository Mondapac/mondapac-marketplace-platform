// seller lists them through Offers. The list starts from the storefront's sample products
// (apps/web/src/storefront/sample-home.ts and sample-catalog.ts: same names, sellers, prices, "was"
// prices and low stock) and adds enough to give every store a full shelf, several products sold by
// more than one store, and a few configurable products with pack sizes. No text uses a claim word
// of the Market: the Halal badge comes from the seller's certificate and the Offer's tag.

/**
 * A product row. category: a category slug of ./catalog.mjs. tax: the Market's tax category
 * code. storage: an option of the storage attribute. variants: [optionCode, label] pairs of a
 * configurable product (attribute pack-size, or volume for drinks); none for a simple product.
 * image: a picture in apps/web/public/placeholders (the storefront sample's photos).
 */
