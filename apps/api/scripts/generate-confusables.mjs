// Generates apps/api/src/modules/certification/domain/generated/uts39-confusables.ts from the
// Unicode UTS #39 confusables.txt (issue #133). Usage, from apps/api:
//   node scripts/generate-confusables.mjs [path-to-confusables.txt]
// With no path the pinned release is downloaded from the unicode-org/unicodetools repository (the
// same file unicode.org publishes). The SHA-256 must match the pin either way, so a changed or
// truncated source never reaches the table. Bump VERSION, URL and SHA256 together, regenerate, and
// get Hassan's review with the corpus (claim-text-data.ts header).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = '17.0.0';
const URL = `https://raw.githubusercontent.com/unicode-org/unicodetools/main/unicodetools/data/security/${VERSION}/confusables.txt`;
const SHA256 = '091c7f82fc39ef208faf8f94d29c244de99254675e09de163160c810d13ef22a';
const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src/modules/certification/domain/generated/uts39-confusables.ts',
);

const source = process.argv[2]
  ? readFileSync(process.argv[2])
  : Buffer.from(await (await fetch(URL)).arrayBuffer());
const digest = createHash('sha256').update(source).digest('hex');
if (digest !== SHA256) {
  throw new Error(`confusables.txt ${VERSION}: SHA-256 ${digest} does not match the pin ${SHA256}`);
}

const text = source.toString('utf8');
const date = /^# Date: (.+)$/m.exec(text)?.[1] ?? 'unknown';
const hex = (cps) => cps.map((cp) => `\\u{${cp.toString(16)}}`).join('');
const rows = [];
for (const line of text.split('\n')) {
  const data = line.replace(/#.*/, '').trim();
  if (data === '') continue;
  const [from, to] = data.split(';').map((field) => field.trim());
  const sourceCps = from.split(/\s+/).map((h) => Number.parseInt(h, 16));
  const targetCps = to.split(/\s+/).map((h) => Number.parseInt(h, 16));
  if (sourceCps.length !== 1 || targetCps.some(Number.isNaN)) {
    throw new Error(`unexpected confusables row: ${line}`);
  }
  rows.push([sourceCps[0], targetCps]);
}
rows.sort((a, b) => a[0] - b[0]);

const body = rows.map(([from, to]) => `  ['${hex([from])}', '${hex(to)}'],`).join('\n');
writeFileSync(
  OUT,
  `// GENERATED by apps/api/scripts/generate-confusables.mjs: do not edit by hand.
// Source: Unicode UTS #39 confusables.txt, version ${VERSION} (${date}),
// SHA-256 ${SHA256}.
// © Unicode®, Inc. Used under the Unicode License v3 (https://www.unicode.org/license.txt);
// see https://www.unicode.org/terms_of_use.html.

/** UTS #39 version of {@link UTS39_CONFUSABLES}. */
export const UTS39_VERSION = '${VERSION}';

/**
 * The full UTS #39 confusable mapping: one source code point to its prototype (one or more code
 * points, NFD), ${rows.length} rows. The matcher's skeleton applies it (claim-text-matcher.ts).
 */
export const UTS39_CONFUSABLES: ReadonlyMap<string, string> = new Map([
${body}
]);
`,
);
console.log(`wrote ${rows.length} rows to ${OUT}`);
